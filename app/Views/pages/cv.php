    function getHtml2CanvasOptions() {
      return {
        scale: 2,
        useCORS: true,
        logging: false,
        windowWidth: 1200,
        onclone: function (clonedDoc) {
          // Fix gradient text for h1
          const h1 = clonedDoc.querySelector('.sidebar-header h1');
          if (h1) {
            h1.style.background = 'none';
            h1.style.webkitBackgroundClip = 'initial';
            h1.style.webkitTextFillColor = 'initial';
            h1.style.color = '#ffffff';
          }
          
          // Inject styles to fix animations and forced desktop layout
          const style = clonedDoc.createElement('style');
          style.innerHTML = `
            .profile-img-wrapper::before { animation: none !important; transform: none !important; background: var(--primary) !important; }
            .progress-fill::after { animation: none !important; display: none !important; }
            .cv-wrapper { max-width: 1200px !important; width: 1200px !important; margin: 0 !important; border-radius: 0 !important; box-shadow: none !important; }
            body { background: #ffffff !important; }
          `;
          clonedDoc.head.appendChild(style);
        }
      };
    }

    function downloadPDF() {
      const element = document.querySelector('.cv-wrapper');
      
      const opt = {
        margin:       [0.4, 0, 0.4, 0],
        filename:     'CV_Francisco_Reyes.pdf',
        image:        { type: 'jpeg', quality: 0.98 },
        html2canvas:  getHtml2CanvasOptions(),
        jsPDF:        { unit: 'in', format: 'letter', orientation: 'portrait' },
        pagebreak:    { mode: ['css', 'legacy'], avoid: ['.timeline-item', '.project-card', '.sidebar-section', '.skill-item'] }
      };

      html2pdf().set(opt).from(element).save();
    }

    function downloadPNG() {
      const element = document.querySelector('.cv-wrapper');

      html2canvas(element, getHtml2CanvasOptions()).then(canvas => {
        const link = document.createElement('a');
        link.download = 'CV_Francisco_Reyes.png';
        link.href = canvas.toDataURL('image/png');
        link.click();
      });
    }
